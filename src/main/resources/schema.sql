CREATE TABLE customer (
  id           BIGINT PRIMARY KEY,
  name         VARCHAR(120) NOT NULL,
  tenant_code  VARCHAR(20)  NOT NULL UNIQUE
);
CREATE TABLE learner (
  id           BIGINT PRIMARY KEY,
  customer_id  BIGINT NOT NULL REFERENCES customer(id),
  name         VARCHAR(120) NOT NULL,
  email        VARCHAR(160) NOT NULL UNIQUE,
  group_name   VARCHAR(60)  NOT NULL
);
CREATE TABLE course (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(40)  NOT NULL UNIQUE,
  title            VARCHAR(200) NOT NULL,
  description      VARCHAR(1000),
  status           VARCHAR(20)  NOT NULL,
  target_group     VARCHAR(60)  NOT NULL,
  manifest_version VARCHAR(20),
  imported_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE lesson (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
  position   INT NOT NULL,
  title      VARCHAR(200) NOT NULL,
  href       VARCHAR(200) NOT NULL,
  body       VARCHAR(4000)
);
CREATE TABLE question (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
  position   INT NOT NULL,
  text       VARCHAR(400) NOT NULL,
  options    VARCHAR(800) NOT NULL,
  correct    INT NOT NULL
);
CREATE TABLE enrollment (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  learner_id   BIGINT NOT NULL REFERENCES learner(id),
  course_id    BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
  valid_until  DATE NOT NULL,
  UNIQUE (learner_id, course_id)
);
CREATE TABLE quiz_attempt (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id  BIGINT NOT NULL REFERENCES enrollment(id) ON DELETE CASCADE,
  correct        INT NOT NULL,
  total          INT NOT NULL,
  score_percent  INT NOT NULL,
  passed         BOOLEAN NOT NULL,
  submitted_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ticket (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_key     VARCHAR(20)  NOT NULL UNIQUE,
  customer_id    BIGINT NOT NULL REFERENCES customer(id),
  summary        VARCHAR(200) NOT NULL,
  description    VARCHAR(2000) NOT NULL,
  impact         INT NOT NULL,
  urgency        INT NOT NULL,
  priority       VARCHAR(4)  NOT NULL,
  status         VARCHAR(20) NOT NULL,
  team           VARCHAR(20) NOT NULL,
  error_code     VARCHAR(20),
  request_id     VARCHAR(40),
  kb_slug        VARCHAR(60),
  root_cause     VARCHAR(2000),
  workaround     VARCHAR(2000),
  resolution     VARCHAR(2000),
  created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ticket_event (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  BIGINT NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
  at         TIMESTAMP WITH TIME ZONE NOT NULL,
  actor      VARCHAR(60) NOT NULL,
  kind       VARCHAR(20) NOT NULL,
  text       VARCHAR(2000) NOT NULL
);
CREATE INDEX idx_enrollment_course ON enrollment(course_id);
CREATE INDEX idx_attempt_enrollment ON quiz_attempt(enrollment_id);
CREATE INDEX idx_ticket_status ON ticket(status);
